void main(){
    // condicionales

    //condicional simple if
    if(45 > 25){
      print("si es mayor");
    }

    //condicional compuesto if-else
    if(45 > 25){
      print("si es mayor");
    }
    else{
      print("no es mayor");
    }

    // condicionales if anidados
    if(45 > 25){
      print("si es mayor");
    }
    else if(45 == 25){
      print("no es mayor");
    }else{
      print("no permtenece");
    }

    //if ternario
  
    print((45 > 25) ? "si es mayor" : "no es mayor");

    // switch-case
    int numero = 1;
    switch(numero){
      case 1:
      print("numero uno");
      //..... comparacion de casos
      break;
    }



}